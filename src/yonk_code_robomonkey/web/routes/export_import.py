def _serialize_value(val: Any) -> Any:
    """Convert a single Python/asyncpg value to a JSON-safe representation."""
    if val is None:
        return None
    if isinstance(val, uuid.UUID):
        return str(val)
    if isinstance(val, datetime):
        return val.isoformat()
    if isinstance(val, date):
        return val.isoformat()
    if isinstance(val, (list, tuple)):
        return [_serialize_value(v) for v in val]
    if isinstance(val, dict):
        return {k: _serialize_value(v) for k, v in val.items()}
    if isinstance(val, (int, float, str, bool)):
        return val
    # asyncpg returns pgvector values as strings like "[0.1,0.2,...]"
    # or as a list of floats. Handle both.
    return str(val)


def _serialize_record(record: asyncpg.Record) -> dict[str, Any]:
    """Convert an asyncpg Record to a JSON-safe dict."""
    return {key: _serialize_value(record[key]) for key in record.keys()}


async def _get_table_columns(
    conn: asyncpg.Connection, schema_name: str, table_name: str
) -> list[dict[str, str]]:
    """Get column names and types for a table."""
    rows = await conn.fetch(
        """
        SELECT column_name, data_type, udt_name
        FROM information_schema.columns
        WHERE table_schema = $1 AND table_name = $2
        ORDER BY ordinal_position
        """,
        schema_name,
        table_name,
    )
    return [
        {"name": r["column_name"], "type": r["data_type"], "udt": r["udt_name"]}
        for r in rows
    ]


def _parse_vector_string(s: str) -> list[float]:
    """Parse a pgvector string like '[0.1,0.2,0.3]' into a float list."""
    s = s.strip()
    if s.startswith("[") and s.endswith("]"):
        s = s[1:-1]
    return [float(x) for x in s.split(",") if x.strip()]


def _coerce_value(val: Any, udt: str) -> Any:
    """Coerce a JSON-deserialized value back to a Python type suitable for asyncpg."""
    if val is None:
        return None

    if udt == "uuid":
        return uuid.UUID(val) if isinstance(val, str) else val

    if udt == "timestamptz" or udt == "timestamp":
        if isinstance(val, str):
            # Handle ISO format strings
            return datetime.fromisoformat(val.replace("Z", "+00:00"))
        return val

    if udt in ("jsonb", "json"):
        # asyncpg expects a JSON string for jsonb columns
        if isinstance(val, (dict, list)):
            return json.dumps(val)
        return val

    if udt == "tsvector":
        # tsvector is auto-generated by triggers — skip it
        return None

    if udt.startswith("vector"):
        # pgvector: asyncpg expects a string like '[0.1,0.2,...]'
        if isinstance(val, list):
            return "[" + ",".join(str(f) for f in val) + "]"
        if isinstance(val, str):
            return val
        return str(val)

    if udt in ("int4", "int8", "int2"):
        return int(val) if val is not None else None

    if udt in ("float4", "float8", "numeric"):
        return float(val) if val is not None else None

    if udt == "bool":
        if isinstance(val, str):
            return val.lower() in ("true", "1", "t")
        return bool(val)

    return val


